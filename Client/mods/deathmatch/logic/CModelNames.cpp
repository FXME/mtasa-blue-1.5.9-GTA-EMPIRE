//
// Get a model ID from its name (case insensitive)
//
uint32 CModelNames::GetModelID(const SString& strName)
{
    InitializeMaps();
    uint32* pusModelID = MapFind(ms_NameModelIDMap, strName.ToLower());
    if (pusModelID)
        return *pusModelID;
    return INVALID_MODEL_ID;
}

//
// Get a clothes texture ID from its name (case insensitive)
//
uint32 CModelNames::GetClothesTexID(const SString& strName)
{
    InitializeMaps();
    uint32* pusModelID = MapFind(ms_NameClothesTexIDMap, strName.ToLower());
    if (pusModelID)
        return *pusModelID;
    return INVALID_MODEL_ID;
}

//
// Get a model name from its ID
//
const char* CModelNames::GetModelName(uint32 usModelID)
{
    InitializeMaps();
    const char** pszName = MapFind(ms_ModelIDNameMap, usModelID);
    if (pszName)
        return *pszName;
    return "";
}

//
// Get a model ID from a string which could be a name or a number.
// If the name starts with "txd", assume it's refering to a global txd
//
uint32 CModelNames::ResolveModelID(const SString& strModelName)
{
    // Check if it's a number
    bool bIsNumber = true;
    for (int i = strModelName.length() - 1; i >= 0 && bIsNumber; i--)
        if (!isdigit((uchar)strModelName[i]))
            bIsNumber = false;

    if (bIsNumber)
        return atoi(strModelName);

    // Check if it starts with "txd"
    if (strModelName.BeginsWithI("txd"))
    {
        uint32 usModelID = atoi(strModelName.SubStr(3));
        if (usModelID)
            return g_pGame->GetBaseIDforTXD() + usModelID;            // Encode global txd as model id 20000+
    }

    // Now search for the name
    return GetModelID(strModelName);
}

//
// Get a file ID in player.img from a string which could be a name or a number.
//
uint32 CModelNames::ResolveClothesTexID(const SString& strTexNameOrNumber)
{
    // Check if it's a number
    uint bHasOnlyDigits = (!strTexNameOrNumber.empty() && strTexNameOrNumber.find_first_not_of("0123456789") == SString::npos);
    if (bHasOnlyDigits)
        return atoi(strTexNameOrNumber);

    // Now search for the name
    return GetClothesTexID(strTexNameOrNumber);
}

//
// Initialize id <-> name maps
//
void CModelNames::InitializeMaps()
{
    if (!ms_ModelIDNameMap.empty())
        return;

    for (uint i = 0; i < NUMELMS(bigFOTable); i++)
    {
        ushort      usID = bigFOTable[i].usID;
        const char* szName = bigFOTable[i].szName;
        MapSet(ms_ModelIDNameMap, usID, szName);
        MapSet(ms_NameModelIDMap, SStringX(szName).ToLower(), usID);
    }

    // Include vehicle names as well
    for (uint i = 400; i <= 610; i++)
    {
        ushort      usID = i;
        const char* szName = CVehicleNames::GetVehicleName(i);
        MapSet(ms_ModelIDNameMap, usID, szName);
        MapSet(ms_NameModelIDMap, SStringX(szName).ToLower(), usID);
    }

    assert(NUMELMS(playerClothesModel) == CLOTHES_MODEL_ID_LAST - CLOTHES_MODEL_ID_FIRST + 1);
    assert(NUMELMS(playerClothesTex) == CLOTHES_TEX_ID_LAST - CLOTHES_TEX_ID_FIRST + 1);

    // Make clothes maps
    for (uint i = 0; i < NUMELMS(playerClothesModel); i++)
    {
        ushort      usID = CLOTHES_MODEL_ID_FIRST + i;
        const char* szName = playerClothesModel[i];
        MapSet(ms_ClothesModelIDNameMap, usID, szName);
        MapSet(ms_NameClothesModelIDMap, SStringX(szName).ToLower(), usID);
    }

    for (uint i = 0; i < NUMELMS(playerClothesTex); i++)
    {
        ushort      usID = CLOTHES_TEX_ID_FIRST + i;
        const char* szName = playerClothesTex[i];
        MapSet(ms_ClothesTexIDNameMap, usID, szName);
        MapSet(ms_NameClothesTexIDMap, SStringX(szName).ToLower(), usID);
    }
}
